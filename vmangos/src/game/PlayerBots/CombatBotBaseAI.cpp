void CombatBotBaseAI::ActivateNearbyAreaTrigger()
{
    for (auto const& itr : sObjectMgr.GetAreaTriggersMap())
    {
        AreaTriggerEntry const* pTrigger = &itr.second;
        if (!pTrigger)
            continue;

        if (!IsPointInAreaTriggerZone(pTrigger, me->GetMapId(), me->GetPositionX(), me->GetPositionY(), me->GetPositionZ(), 5.0f))
            continue;

        SendAreaTriggerPacket(pTrigger->id);
        break;
    }
}

void CombatBotBaseAI::OnPacketReceived(WorldPacket const* packet)
{
    // Must always check "me" player pointer here!
    //printf("Bot received %s\n", LookupOpcodeName(packet->GetOpcode()));
    switch (packet->GetOpcode())
    {
        case SMSG_NEW_WORLD:
        {
            if (!me)
                return;

            std::unique_ptr<WorldPacket> data = std::make_unique<WorldPacket>(MSG_MOVE_WORLDPORT_ACK);
            me->GetSession()->QueuePacket(std::move(data));
            break;
        }
        case MSG_MOVE_TELEPORT_ACK:
        {
            if (!me)
                return;

            std::unique_ptr<WorldPacket> data = std::make_unique<WorldPacket>(MSG_MOVE_TELEPORT_ACK);
            *data << me->GetObjectGuid();
#if SUPPORTED_CLIENT_BUILD > CLIENT_BUILD_1_9_4
            *data << me->GetLastCounterForMovementChangeType(TELEPORT);
#endif
            *data << uint32(time(nullptr));
            me->GetSession()->QueuePacket(std::move(data));
            break;
        }
        case SMSG_LOGIN_SETTIMESPEED:
        {
            if (!me)
                return;

            UpdateVisualHonorRankBasedOnItems();
            break;
        }
        case SMSG_TRADE_STATUS:
        {
            if (!me)
                return;

            uint32 status = *((uint32*)(*packet).contents());
            if (status == TRADE_STATUS_BEGIN_TRADE)
            {
                std::unique_ptr<WorldPacket> data = std::make_unique<WorldPacket>(CMSG_BEGIN_TRADE);
                me->GetSession()->QueuePacket(std::move(data));
            }
            else if (status == TRADE_STATUS_TRADE_ACCEPT)
            {
                std::unique_ptr<WorldPacket> data = std::make_unique<WorldPacket>(CMSG_ACCEPT_TRADE);
                *data << uint32(1);
                me->GetSession()->QueuePacket(std::move(data));
            }
            else if (status == TRADE_STATUS_TRADE_COMPLETE)
            {
                EquipOrUseNewItem();
                UpdateVisualHonorRankBasedOnItems();
            }
            break;
        }
        case SMSG_RESURRECT_REQUEST:
        {
            if (!me)
                return;

            std::unique_ptr<WorldPacket> data = std::make_unique<WorldPacket>(CMSG_RESURRECT_RESPONSE);
            *data << me->GetResurrector();
            *data << uint8(1);
            me->GetSession()->QueuePacket(std::move(data));
            break;
        }
        case SMSG_BATTLEFIELD_STATUS:
        {
            if (!me)
                return;

            if (me->IsBeingTeleported() || me->InBattleGround())
                m_receivedBgInvite = false;
            else
            {
                for (uint32 i = BATTLEGROUND_QUEUE_AV; i <= BATTLEGROUND_QUEUE_AB; i++)
                {
                    if (me->IsInvitedForBattleGroundQueueType(BattleGroundQueueTypeId(i)))
                    {
                        m_receivedBgInvite = true;
                        break;
                    }
                }
            }
            return;
        }
        case SMSG_LOOT_START_ROLL:
        {
            if (!me)
                return;

            uint64 guid = *((uint64*)(*packet).contents());
            uint32 slot = *(((uint32*)(*packet).contents()) + 2);
            uint32 itemId = *(((uint32*)(*packet).contents()) + 3);

            uint8 rollType = 0; // default: pass

            // Guild bots: roll Need if the item is an upgrade for their spec
            if (sGuildBotMgr.IsGuildBot(me->GetGUIDLow()))
            {
                // Check if any human player is in the group and might need it
                // Guild bots never contest a human Need roll — we pass by default
                // and let CountTheRoll handle it. But we do roll Need if it's an upgrade.
                bool humanInGroup = false;
                if (Group* group = me->GetGroup())
                {
                    for (auto itr = group->GetFirstMember(); itr != nullptr; itr = itr->next())
                    {
                        if (Player* member = itr->getSource())
                        {
                            if (member->GetGUIDLow() != me->GetGUIDLow() &&
                                !sGuildBotMgr.IsGuildBot(member->GetGUIDLow()) &&
                                member->GetSession() && !member->GetSession()->GetBot())
                            {
                                humanInGroup = true;
                                break;
                            }
                        }
                    }
                }

                // Only roll Need if item is an upgrade — but pass if humans are present
                // (humans always get priority; bots pick up leftovers)
                if (!humanInGroup)
                {
                    // Evaluate across all equippable slots for this item
                    ItemPrototype const* pProto = sObjectMgr.GetItemPrototype(itemId);
                    if (pProto)
                    {
                        for (uint8 equipSlot = EQUIPMENT_SLOT_START; equipSlot < EQUIPMENT_SLOT_END; ++equipSlot)
                        {
                            float delta = sGuildBotMgr.EvaluateUpgrade(me->GetGUIDLow(), itemId, equipSlot);
                            if (delta > 0.0f)
                            {
                                rollType = 1; // ROLL_NEED
                                break;
                            }
                        }
                    }
                }
            }

            std::unique_ptr<WorldPacket> data = std::make_unique<WorldPacket>(CMSG_LOOT_ROLL);
            *data << uint64(guid);
            *data << uint32(slot);
            *data << uint8(rollType);
            me->GetSession()->QueuePacket(std::move(data));
            return;
        }
    }
}
