#!/usr/bin/env python3
"""Generate DBC parity goldens for mangos-dbc from production fixtures.

Independent oracle: parses WDBC via scripts/dbc.py plus a fmt-aware
produced-row digest reimplementing AutoProduceData semantics.
Output: JSON consumed by crates/mangos-dbc/tests/production_dbc.rs.
"""

import hashlib
import json
import os
import re
import struct
import sys

sys.path.insert(0, "scripts")
import dbc as dbcmod

DBC_DIR = sys.argv[1]
FORMATS_RS = "vmangos-rs/crates/mangos-dbc/src/formats.rs"

rust_src = open(FORMATS_RS).read()
STORE_FMTS = {
    file: fmt
    for _name, file, fmt in re.findall(
        r'pub const (\w+): StoreDef = StoreDef \{\s*file: "([^"]+)",\s*fmt: "([^"]*)",\s*\};',
        rust_src,
    )
}


def produced_digest(records, string_block, fmt):
    h = hashlib.sha256()
    for rec in records:
        for x, kind in enumerate(fmt):
            v = rec[x]
            if kind in "xf":  # ignored / float-as-raw handled below
                if kind == "f":
                    h.update(b"f")
                    h.update(struct.pack("<f", struct.unpack("<f", struct.pack("<I", v))[0]))
            elif kind in "in":
                h.update(b"i")
                h.update(struct.pack("<I", v))
            elif kind == "s":
                h.update(b"s")
                end = string_block.index(b"\x00", v)
                h.update(string_block[v:end])
                h.update(b"\x00")
            elif kind == "d":
                pass  # sort key excluded from produced data
            else:
                raise AssertionError(f"unexpected fmt char {kind!r}")
    return h.hexdigest()


out = {"stores": {}, "files": {}}
for fname in sorted(os.listdir(DBC_DIR)):
    if not fname.endswith(".dbc"):
        continue
    path = os.path.join(DBC_DIR, fname)
    raw = open(path, "rb").read()
    if len(raw) == 0:
        # Zero-byte extraction artifacts in the production set; the C++
        # loader rejects them (fread of the header fails).
        out["files"][fname] = {"empty_file": True}
        continue
    assert raw[:4] == b"WDBC", fname
    rc, fc, rs, ss = struct.unpack_from("<4I", raw, 4)
    if rs % 4 != 0:
        # Byte-field file (CharBaseInfo.dbc): scripts/dbc.py cannot model
        # sub-u32 fields; header-level golden only. No server store loads it.
        out["files"][fname] = {
            "record_count": rc,
            "field_count": fc,
            "record_size": rs,
            "string_size": ss,
            "records_sha256": hashlib.sha256(raw[20 : 20 + rc * rs]).hexdigest(),
            "strings_sha256": hashlib.sha256(raw[20 + rc * rs : 20 + rc * rs + ss]).hexdigest(),
            "byte_fields": True,
        }
        continue
    records, string_block = dbcmod.read_dbc(path)
    assert len(records) == rc and len(string_block) == ss, fname
    rec_section = raw[20 : 20 + rc * rs]
    entry = {
        "record_count": rc,
        "field_count": fc,
        "record_size": rs,
        "string_size": ss,
        "records_sha256": hashlib.sha256(rec_section).hexdigest(),
        "strings_sha256": hashlib.sha256(string_block).hexdigest(),
    }
    out["files"][fname] = entry
    if fname in STORE_FMTS:
        fmt = STORE_FMTS[fname]
        assert len(fmt) == fc, (fname, fmt, fc)
        assert rs == fc * 4, (fname, rs, fc)
        max_index = None
        for x, kind in enumerate(fmt):
            if kind in "nd":
                max_index = max((r[x] for r in records), default=0)
        out["stores"][fname] = {
            "fmt": fmt,
            "max_index": max_index,
            "produced_sha256": produced_digest(records, string_block, fmt),
        }

print(f"files: {len(out['files'])}, stores: {len(out['stores'])}")
with open(sys.argv[2], "w") as f:
    json.dump(out, f, indent=1, sort_keys=True)
print("golden written")


# Also emit a dependency-free Rust golden table next to the JSON.
def lit(n):
    return f"{n:,}".replace(",", "_")


def emit_rust(out, path):
    lines = [
        "// Generated by vmangos-rs/scripts/dbc_oracle_gen.py from the",
        "// production DataDir fixtures via scripts/dbc.py. Do not edit.",
        "",
        "pub struct FileGolden {",
        "    pub name: &'static str,",
        "    pub empty_file: bool,",
        "    pub record_count: u32,",
        "    pub field_count: u32,",
        "    pub record_size: u32,",
        "    pub string_size: u32,",
        "    pub records_sha256: &'static str,",
        "    pub strings_sha256: &'static str,",
        "}",
        "",
        "pub struct StoreGolden {",
        "    pub file: &'static str,",
        "    pub max_index: Option<u32>,",
        "    pub produced_sha256: &'static str,",
        "}",
        "",
        "pub const FILES: &[FileGolden] = &[",
    ]
    for name in sorted(out["files"]):
        v = out["files"][name]
        if v.get("empty_file"):
            lines.append(
                f'    FileGolden {{ name: "{name}", empty_file: true, record_count: 0, field_count: 0, record_size: 0, string_size: 0, records_sha256: "", strings_sha256: "" }},'
            )
        else:
            lines.append(
                f'    FileGolden {{ name: "{name}", empty_file: false, record_count: {lit(v["record_count"])}, field_count: {lit(v["field_count"])}, record_size: {lit(v["record_size"])}, string_size: {lit(v["string_size"])}, records_sha256: "{v["records_sha256"]}", strings_sha256: "{v["strings_sha256"]}" }},'
            )
    lines.append("];")
    lines.append("")
    lines.append("pub const STORES: &[StoreGolden] = &[")
    for name in sorted(out["stores"]):
        v = out["stores"][name]
        max_index = f"Some({v['max_index']})" if v["max_index"] is not None else "None"
        lines.append(
            f'    StoreGolden {{ file: "{name}", max_index: {max_index}, produced_sha256: "{v["produced_sha256"]}" }},'
        )
    lines.append("];")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


if len(sys.argv) > 3:
    emit_rust(out, sys.argv[3])
    print("rust golden written")
