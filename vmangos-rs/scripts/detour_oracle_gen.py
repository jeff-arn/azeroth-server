#!/usr/bin/env python3
"""Generate Detour FFI parity goldens for mangos-detour.

Compiles scripts/detour_oracle.cpp against the vendored Detour
sources (same flags as the crate's build.rs), runs it over a
fixed production tile set from the dev-bench fixtures, and emits
crates/mangos-detour/tests/detour_oracle.rs (+ .json).

Usage: detour_oracle_gen.py <mmaps_dir>
"""

import json
import subprocess
import sys
import tempfile

DETOUR = "vmangos/dep/recastnavigation/Detour"
SOURCES = [
    "DetourAlloc.cpp",
    "DetourAssert.cpp",
    "DetourCommon.cpp",
    "DetourNavMesh.cpp",
    "DetourNavMeshQuery.cpp",
    "DetourNode.cpp",
]
PARAMS = "000.mmap"
TILES = ["0002239.mmtile", "0002240.mmtile", "0002338.mmtile", "0002339.mmtile", "0002340.mmtile"]
OUT_RS = "vmangos-rs/crates/mangos-detour/tests/detour_oracle.rs"
OUT_JSON = "vmangos-rs/crates/mangos-detour/tests/detour_oracle.json"


def hx(v):
    return f"0x{v >> 16:04X}_{v & 0xFFFF:04X}"


def hx64(v):
    return f"0x{(v >> 48) & 0xFFFF:04X}_{(v >> 32) & 0xFFFF:04X}_{(v >> 16) & 0xFFFF:04X}_{v & 0xFFFF:04X}"


def tupl3(t):
    return "(" + ", ".join(hx(v) for v in t) + ")"


def emit_rs(data):
    lines = [
        "// Generated by vmangos-rs/scripts/detour_oracle_gen.py — goldens from",
        "// the independent C++ harness scripts/detour_oracle.cpp over",
        "// production mmap fixtures. Do not edit.",
        "",
        f'pub const PARAMS_FILE: &str = "{PARAMS}";',
        "pub const TILE_FILES: &[&str] = &[" + ", ".join(f'"{t}"' for t in TILES) + "];",
        f"pub const TILES_OK: i32 = {data['tiles_ok']};",
        "",
        "// (query xyz bits, poly ref, closest xyz bits, dist bits)",
        "pub type NearGolden = ((u32, u32, u32), u64, (u32, u32, u32), u32);",
        "pub const NEAR: &[NearGolden] = &[",
    ]
    for q in data["near"]:
        lines.append(f"    ({tupl3(q['q'])}, {hx64(q['ref'])}, {tupl3(q['c'])}, {hx(q['d'])}),")
    lines.append("];")
    lines.append("")
    lines.append("pub struct PathGolden {")
    lines.append("    pub start: (u32, u32, u32),")
    lines.append("    pub end: (u32, u32, u32),")
    lines.append("    pub start_ref: u64,")
    lines.append("    pub end_ref: u64,")
    lines.append("    pub status: u32,")
    lines.append("    pub refs: &'static [u64],")
    lines.append("    pub straight_status: u32,")
    lines.append("    pub points: &'static [(u32, u32, u32)],")
    lines.append("}")
    lines.append("")
    lines.append("pub const PATHS: &[PathGolden] = &[")
    for p in data["paths"]:
        lines.append("    PathGolden {")
        lines.append(f"        start: {tupl3(p['s'])},")
        lines.append(f"        end: {tupl3(p['e'])},")
        lines.append(f"        start_ref: {hx64(p['sref'])},")
        lines.append(f"        end_ref: {hx64(p['eref'])},")
        lines.append(f"        status: {hx(p['status'])},")
        lines.append("        refs: &[" + ", ".join(hx64(r) for r in p["refs"]) + "],")
        lines.append(f"        straight_status: {hx(p['sstatus'])},")
        lines.append("        points: &[" + ", ".join(tupl3(t) for t in p["pts"]) + "],")
        lines.append("    },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main():
    mmaps_dir = sys.argv[1]
    with tempfile.TemporaryDirectory() as tmp:
        exe = f"{tmp}/detour_oracle"
        cmd = (
            ["c++", "-O2", "-ffp-contract=off", "-std=c++14", "-I", f"{DETOUR}/Include"]
            + [f"{DETOUR}/Source/{s}" for s in SOURCES]
            + ["vmangos-rs/scripts/detour_oracle.cpp", "-o", exe]
        )
        subprocess.run(cmd, check=True)
        out = subprocess.run([exe, mmaps_dir, PARAMS] + TILES, check=True, capture_output=True, text=True).stdout
    data = json.loads(out)
    with open(OUT_JSON, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=1)
    with open(OUT_RS, "w", encoding="utf-8") as fh:
        fh.write(emit_rs(data))
    ok_paths = sum(1 for p in data["paths"] if p["status"] & (1 << 30))
    print(f"tiles_ok={data['tiles_ok']} near={len(data['near'])} paths={len(data['paths'])} ok_paths={ok_paths}")


if __name__ == "__main__":
    main()
