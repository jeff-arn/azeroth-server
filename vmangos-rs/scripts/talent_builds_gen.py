#!/usr/bin/env python3
"""Generate the Rust talent-build tables for mangos-bots.

Source of truth: the checked-in C++ tables in
vmangos/src/game/PlayerBots/CombatBotBaseAI.cpp (themselves
generated by scripts/generate_talent_builds.py from DBC data —
that script's DBC path is droplet-bound, so this generator
transcribes the deployed C++ arrays mechanically instead).

Output: vmangos-rs/crates/mangos-bots/src/talent_builds.rs
(checked-in data file; regenerate, never hand-edit).
"""

import re

SRC = "vmangos/src/game/PlayerBots/CombatBotBaseAI.cpp"
OUT = "vmangos-rs/crates/mangos-bots/src/talent_builds.rs"

ROLE_ENUM = {
    "ROLE_INVALID": "Role::Invalid",
    "ROLE_MELEE_DPS": "Role::MeleeDps",
    "ROLE_RANGE_DPS": "Role::RangeDps",
    "ROLE_TANK": "Role::Tank",
    "ROLE_HEALER": "Role::Healer",
}

CLASS_ENUM = {
    "CLASS_WARRIOR": "Class::Warrior",
    "CLASS_PALADIN": "Class::Paladin",
    "CLASS_HUNTER": "Class::Hunter",
    "CLASS_ROGUE": "Class::Rogue",
    "CLASS_PRIEST": "Class::Priest",
    "CLASS_SHAMAN": "Class::Shaman",
    "CLASS_MAGE": "Class::Mage",
    "CLASS_WARLOCK": "Class::Warlock",
    "CLASS_DRUID": "Class::Druid",
}


def main():
    text = open(SRC, encoding="utf-8").read()

    arrays = {}
    for name, body in re.findall(r"static BotTalentPoint const (s_\w+)\[\] = \{(.*?)\};", text, re.S):
        points = [(int(t), int(r)) for t, r in re.findall(r"\{(\d+),\s*(\d+)\}", body)]
        arrays[name] = points

    master = re.search(r"s_talentBuilds\[\] = \{(.*?)^\};", text, re.S | re.M)
    assert master, "master table not found"
    builds = re.findall(
        r"\{(CLASS_\w+),\s*(ROLE_\w+),\s*\"([^\"]+)\",\s*(s_\w+),",
        master.group(1),
    )
    assert len(builds) == 26, f"expected 26 builds, got {len(builds)}"
    for _cls, _role, _name, arr in builds:
        assert arr in arrays, f"missing point array {arr}"

    lines = [
        "// Generated by vmangos-rs/scripts/talent_builds_gen.py from the",
        f"// checked-in C++ tables in {SRC} (themselves generated by",
        "// scripts/generate_talent_builds.py). Do not edit.",
        "",
        "use crate::talents::TalentBuild;",
        "use crate::{Class, Role};",
        "",
        "/// All 26 premade builds (`s_talentBuilds`).",
        "pub const TALENT_BUILDS: &[TalentBuild] = &[",
    ]
    for cls, role, name, arr in builds:
        pts = ", ".join(f"({t}, {r})" for t, r in arrays[arr])
        lines.append("    TalentBuild {")
        lines.append(f"        class: {CLASS_ENUM[cls]},")
        lines.append(f"        role: {ROLE_ENUM[role]},")
        lines.append(f'        name: "{name}",')
        lines.append(f"        points: &[{pts}],")
        lines.append("    },")
    lines.append("];")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    totals = [sum(r for _t, r in arrays[a]) for _c, _r, _n, a in builds]
    print(f"builds={len(builds)} rank-totals={sorted(set(totals))}")


if __name__ == "__main__":
    main()
