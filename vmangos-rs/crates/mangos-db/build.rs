//! Generates the expected-migration lists exactly like
//! `vmangos/cmake/generators/migrations_list.h.cmake`: glob
//! `vmangos/sql/migrations/*.sql`, split each filename at its
//! last `_` into (migration name, database key), and emit one
//! name array per database. The C++ writes the same lists into
//! a generated header at build time; nothing is checked in.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let migrations_dir = manifest_dir.join("../../../vmangos/sql/migrations");
    println!("cargo:rerun-if-changed={}", migrations_dir.display());

    let mut by_db: BTreeMap<String, Vec<String>> = BTreeMap::new();
    match std::fs::read_dir(&migrations_dir) {
        Ok(entries) => {
            for entry in entries.flatten() {
                let file_name = entry.file_name();
                let Some(name) = file_name.to_str() else {
                    continue;
                };
                let Some(stem) = name.strip_suffix(".sql") else {
                    continue;
                };
                let Some((migration, db_key)) = stem.rsplit_once('_') else {
                    continue;
                };
                by_db
                    .entry(db_key.to_string())
                    .or_default()
                    .push(migration.to_string());
            }
        }
        Err(err) => {
            println!(
                "cargo:warning=migrations dir {} unreadable ({err}); gate lists will be empty",
                migrations_dir.display()
            );
        }
    }

    let mut out = String::from("// Generated by build.rs; do not edit.\n");
    for (const_name, db_key) in [
        ("MIGRATIONS_WORLD", "world"),
        ("MIGRATIONS_CHARACTERS", "characters"),
        ("MIGRATIONS_LOGON", "logon"),
        ("MIGRATIONS_LOGS", "logs"),
    ] {
        let mut names = by_db.get(db_key).cloned().unwrap_or_default();
        names.sort();
        let _ = writeln!(out, "pub static {const_name}: &[&str] = &[");
        for name in &names {
            let _ = writeln!(out, "    {name:?},");
        }
        out.push_str("];\n");
    }

    let out_path =
        PathBuf::from(std::env::var("OUT_DIR").expect("out dir")).join("migrations_list.rs");
    std::fs::write(out_path, out).expect("write migrations list");
}
